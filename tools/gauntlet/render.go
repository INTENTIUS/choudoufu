func exampleEntryJSON(m *Manifest) string {
	var ex Estate
	for _, e := range m.Estates {
		if e.Set == SetCore && e.URL != "" {
			ex = e
			break
		}
	}
	if ex.Name == "" && len(m.Estates) > 0 {
		ex = m.Estates[0]
	}
	one := &Manifest{Estates: []Estate{ex}}
	b, _ := one.Canonical()
	// Show just the entry, not the wrapper.
	s := string(b)
	start := strings.Index(s, "{\n      \"name\"")
	end := strings.LastIndex(s, "}\n  ]")
	if start < 0 || end < 0 || end <= start {
		return s
	}
	body := s[start : end+1]
	// De-indent by four spaces.
	lines := strings.Split(body, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, "    ")
	}
	return strings.Join(lines, "\n")
}

func mdCell(s string) string {
	if s == "" {
		return ""
	}
	return strings.ReplaceAll(s, "|", "\\|")
}

// estateDateRange returns the oldest and newest last_run.date across every
// estate that has recorded at least one run. ok is false when none has -
// a fresh manifest before its first `gauntlet run`. RFC3339 UTC strings
// (the only format LastRun.Date is ever written in, run.go) sort correctly
// as plain strings, so no time parsing is needed.
func estateDateRange(a *Artifact) (oldest, newest string, ok bool) {
	for _, r := range a.Estates {
		if r.LastRun == nil || r.LastRun.Date == "" {
			continue
		}
		d := r.LastRun.Date
		if !ok || d < oldest {
			oldest = d
		}
		if !ok || d > newest {
			newest = d
		}
		ok = true
	}
	return oldest, newest, ok
}

// emulatorGroup is one distinct emulator digest recorded across the board's
// rows, and how many rows recorded it.
type emulatorGroup struct {
	Emulator string // "" is its own group: a row that ran but recorded no digest
	Count    int
}

// emulatorGroups buckets every estate that has recorded a run by its OWN
// last_run.emulator - the digest that specific run actually launched
// against, stamped by RunEstates at run time (run.go). It never reads
// a.Emulator: that field is configuration (a plain copy of live/floci-image,
// true of the checked-out tree regardless of what has or hasn't run), and
// conflating the two is exactly the shape #414 already found once, one
// field over (top-level Commit/Generated borrowed to describe evidence).
// A row with no last_run is excluded (it has recorded nothing to bucket);
// a row whose last_run has no recorded digest lands in the "" bucket -
// unknown provenance, distinct from and never merged into any real digest.
// Sorted by count descending, ties broken by digest, with the "" bucket
// always last regardless of its count so a board-wide sentence names the
// largest real agreement first.
func emulatorGroups(a *Artifact) []emulatorGroup {
	counts := map[string]int{}
	for _, r := range a.Estates {
		if r.LastRun == nil {
			continue
		}
		counts[r.LastRun.Emulator]++
	}
	var groups []emulatorGroup
	unknown := 0
	for e, n := range counts {
		if e == "" {
			unknown = n
			continue
		}
		groups = append(groups, emulatorGroup{Emulator: e, Count: n})
	}
	sort.Slice(groups, func(i, j int) bool {
		if groups[i].Count != groups[j].Count {
			return groups[i].Count > groups[j].Count
		}
		return groups[i].Emulator < groups[j].Emulator
	})
	if unknown > 0 {
		groups = append(groups, emulatorGroup{Emulator: "", Count: unknown})
	}
	return groups
}

// boardBanner is the one board-wide sentence the index page still gets to
// make, and it may only assert what every row below actually agrees on
// (the standing rule for every rendered claim in this fork: never ship a
// claim the rows underneath cannot support). It used to claim a single "measured
// at commit X" stamp for the whole board; no procedure ever produced that
// fact honestly (#414), so it is gone rather than kept lying. It was then
// fixed to borrow a.Emulator - CONFIGURATION, the pin the next run will use
// - to describe every row's EVIDENCE, which is true for exactly one
// instant (when a full sweep finishes) and false the moment any single
// estate re-runs against a repinned image while the rest sit unrun. That is
// the same defect one layer down, so this reads emulatorGroups (rows) and
// estateDateRange (rows), never a.Emulator, to describe what happened -
// a.Emulator appears only to say what the CURRENT pin is, never to claim a
// past run used it.
//
// Computed fresh from a.Estates on every call, never carried from a
// previous render, so it cannot go stale independently of the table below
// it. Handles: no runs yet; every row agreeing (with or without matching
// the current pin - a fully-agreeing board can still be uniformly stale
// after a repin); and rows disagreeing, which renders as a breakdown
// rather than picking a side.
func boardBanner(a *Artifact) string {
	oldest, newest, ok := estateDateRange(a)
	if !ok {
		return fmt.Sprintf("The pinned emulator image is `%s` (configuration for the next run); no estate below has recorded a run yet.", a.Emulator)
	}
	dateClause := fmt.Sprintf("recorded at %s", oldest)
	if oldest != newest {
		dateClause = fmt.Sprintf("recorded between %s and %s. Each row below carries its own `last_run` date; they are not all the same run", oldest, newest)
	}

	groups := emulatorGroups(a)
	switch {
	case len(groups) == 1 && groups[0].Emulator == "":
		return fmt.Sprintf("Every estate below has recorded a run, but none recorded which emulator image it used; nothing here confirms whether they matched the current pin `%s`.", a.Emulator)
	case len(groups) == 1:
		digest := groups[0].Emulator
		if digest == a.Emulator {
			return fmt.Sprintf("Every estate below last ran against the pinned emulator image `%s`, %s.", digest, dateClause)
		}
		return fmt.Sprintf("Every estate below last ran against emulator image `%s`, %s. The pin has since moved to `%s`; every row below is stale evidence against the current image.", digest, dateClause, a.Emulator)
	default:
		var parts []string
		for _, g := range groups {
			label := fmt.Sprintf("`%s`", g.Emulator)
			switch {
			case g.Emulator == "":
				label = "an unrecorded image"
			case g.Emulator == a.Emulator:
				label += " (current pin)"
			}
			parts = append(parts, fmt.Sprintf("%d against %s", g.Count, label))
		}
		// A row-disagreement claim needs the same date-range evidence the
		// single-group branches above already carry (dateClause) - found by
		// TestBoardBannerMatchesEstateRows the first time this artifact ever
		// had two distinct last_run.emulator groups at once (#434's own
		// verification run against reference-ec2-vpc and
		// corpus-dynamodb-table-basic): this branch asserted the emulator
		// split but never mentioned when any of it was measured, so the
		// oldest/newest last_run.date the rows actually carry went unstated
		// on the one board-wide sentence that gets to make a claim at all.
		// (#411's own worktree found and fixed the same gap independently,
		// the same night, against #411's own gauntlet run advancing
		// corpus-iam-policy to a new pin - #434's fix landed on main first,
		// so it is what stands here.)
		dateNote := fmt.Sprintf("last_run.date reads %s on every row measured so far", oldest)
		if oldest != newest {
			dateNote = fmt.Sprintf("last_run.date ranges from %s to %s across these rows, not one shared measurement", oldest, newest)
		}
		return fmt.Sprintf("Estates below were last measured against different emulator pins: %s (%s). The current pin is `%s`; a row not measured against it is stale evidence, not a failure - `go run ./tools/gauntlet next` surfaces it as work.", strings.Join(parts, ", "), dateNote, a.Emulator)
	}
}

// runtimeBanner is the one board-wide sentence about wall-clock time this
// page gets to make (#434), held to the same discipline boardBanner already
// holds the emulator/date claims to: it may only assert what the rows below
// actually support, computed fresh from a.Estates on every render rather
// than carried over, so it cannot go stale independently of what it
// summarizes. duration_s (run.go) is new with #434, so most rows will have
// none for a while after this lands - that must read as "partial, N of M
// estates recorded" rather than a "the full board takes N hours" claim no
// single sweep has actually produced (see HANDOFF.md's #414 lesson: no
// procedure runs the whole board in one shot, so no field may claim it did).
func runtimeBanner(a *Artifact) string {
	type group struct {
		total float64
		count int
	}
	groups := map[string]*group{}
	var order []string
	recorded := 0
	for _, r := range a.Estates {
		if r.LastRun == nil || r.LastRun.DurationS <= 0 {
			continue
		}
		recorded++
		g, ok := groups[r.LastRun.Commit]
		if !ok {
			g = &group{}
			groups[r.LastRun.Commit] = g
			order = append(order, r.LastRun.Commit)
		}
		g.total += r.LastRun.DurationS
		g.count++
	}
	if recorded == 0 {
		return "No estate has a recorded `last_run.duration_s` yet; it is populated the next time each estate runs (#434)."
	}
	sort.Strings(order) // commit hashes have no other natural order; sorted only for determinism
	var parts []string
	var grandTotal float64
	for _, c := range order {
		g := groups[c]
		grandTotal += g.total
		parts = append(parts, fmt.Sprintf("%s across %d estate(s) at commit `%s`", formatDuration(g.total), g.count, short(c)))
	}
	missing := len(a.Estates) - recorded
	if len(order) == 1 {
		note := ""
		if missing > 0 {
			note = fmt.Sprintf(" This is not a full-board figure: %d of %d estates have no recorded duration yet.", missing, len(a.Estates))
		}
		return fmt.Sprintf("%d of %d estates have a recorded run duration, totaling %s at commit `%s`.%s", recorded, len(a.Estates), formatDuration(grandTotal), short(order[0]), note)
	}
	return fmt.Sprintf("%d of %d estates have a recorded run duration, totaling %s, but not from one sweep: %s. This total spans different commits, not a single board run, and excludes %d estate(s) with no recorded duration yet.", recorded, len(a.Estates), formatDuration(grandTotal), strings.Join(parts, "; "), missing)
}

// formatDuration renders seconds the way a human reads a stopwatch
// ("3m45s", "1h2m3s"); time.Duration.String() already does exactly this and
// is what a full-board figure needs to read as hours once one exists.
func formatDuration(seconds float64) string {
	if seconds <= 0 {
		return "-"
	}
	return time.Duration(seconds * float64(time.Second)).Round(100 * time.Millisecond).String()
}

// runtimeTotalCell is one estate row's last_run.duration_s, or "-" when this
// run predates #434 or never completed.
func runtimeTotalCell(r EstateResult) string {
	if r.LastRun == nil {
		return "-"
	}
	return formatDuration(r.LastRun.DurationS)
}

// runtimeStageCells lists "<stage id> <duration>" for every active stage
// that recorded one, omitting stages with none rather than padding every
// row with dashes - a row from before #434, or from a script sourcing an
// older live/e2e/lib/gauntlet.sh that does not emit duration_s, legitimately
// has zero of these, and the sentence says so plainly instead of a wall of
// dashes.
func runtimeStageCells(r EstateResult, a *Artifact) string {
	var parts []string
	for _, s := range a.Stages {
		if s.Status != StatusActive {
			continue
		}
		if r.LastRun == nil {
			continue
		}
		secs, ok := r.LastRun.Seconds[s.ID]
		if !ok {
			continue
		}
		parts = append(parts, fmt.Sprintf("%s %s", s.ID, formatDuration(secs)))
	}
	if len(parts) == 0 {
		return "none recorded yet"
	}
	return strings.Join(parts, ", ")
}

// sortedKeys is a map's keys in order, for deterministic rendering.
func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func verdictMark(v string) string {
	switch v {
	case VerdictPass:
		return "pass"
	case VerdictFail:
		return "FAIL"
	case VerdictNA:
		return "n/a"
	default:
		return "not run"
	}
}

func short(sha string) string {
	if len(sha) > 10 {
		return sha[:10]
	}
	return sha
}

func firstSentence(s string) string {
	if i := strings.Index(s, ". "); i > 0 {
		return s[:i+1]
	}
	return s
}
