// LoadScaleArtifact reads live/gauntlet-scale.json, or an empty, correctly-
// versioned ScaleArtifact if the file does not exist yet (the first record
// ever written creates it).
func LoadScaleArtifact(root string) (*ScaleArtifact, error) {
	path := filepath.Join(root, ScaleRecordsPath)
	b, err := os.ReadFile(path) //nolint:gosec // a fixed, repo-relative path
	if err != nil {
		if os.IsNotExist(err) {
			return &ScaleArtifact{Schema: ScaleRecordSchema}, nil
		}
		return nil, err
	}
	var a ScaleArtifact
	if err := json.Unmarshal(b, &a); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return &a, nil
}

// SaveScaleArtifact writes a to live/gauntlet-scale.json, sorted by
// (Estate, Target, Scale) so a diff shows only what actually changed.
// a.Emulator is stamped fresh from live/floci-image on every call - see its
// own doc comment for why this, like Artifact.Emulator, is always the
// CURRENT pin rather than whatever the caller happened to leave it at.
func SaveScaleArtifact(root string, a *ScaleArtifact) error {
	a.Emulator = emulatorPin(root)
	sortScaleRecords(a.Records)
	b, err := json.MarshalIndent(a, "", "  ")
	if err != nil {
		return err
	}
	b = append(b, '\n')
	return os.WriteFile(filepath.Join(root, ScaleRecordsPath), b, 0o644) //nolint:gosec // a committed artifact, not a secret
}

func sortScaleRecords(recs []ScaleRecord) {
	for i := 1; i < len(recs); i++ {
		for j := i; j > 0 && scaleRecordLess(recs[j], recs[j-1]); j-- {
			recs[j], recs[j-1] = recs[j-1], recs[j]
		}
	}
}

func scaleRecordLess(a, b ScaleRecord) bool {
	if a.Estate != b.Estate {
		return a.Estate < b.Estate
	}
	if a.Target != b.Target {
		return a.Target < b.Target
	}
	return a.Scale < b.Scale
}

// UpsertScaleRecord replaces a.Records' entry sharing rec's (Estate, Target,
// Scale) identity, or appends rec if none does - the row-per-size behavior
// LiveCertResult's own row-per-estate SetLiveCertResult deliberately does
// NOT have (see ScaleRecord's own doc comment).
func (a *ScaleArtifact) UpsertScaleRecord(rec ScaleRecord) {
	for i := range a.Records {
		if a.Records[i].Estate == rec.Estate && a.Records[i].Target == rec.Target && a.Records[i].Scale == rec.Scale {
			a.Records[i] = rec
			return
		}
	}
	a.Records = append(a.Records, rec)
}

// UpsertScaleRecordKeepingCallCounts is UpsertScaleRecord for a caller whose
// source cannot measure PlanCalls or AuditCalls at all - which is every
// caller that rebuilds a record from live/gauntlet.json, because that
// artifact has never held a call count. The rebuilt record wins everywhere
// it has a value; the two call-count fields are filled from the existing
// row when the rebuild has none, and overridden when it has one.
//
// Without this, `gauntlet scale-backfill` silently deleted numbers only
// `gauntlet scale-import-slice` can produce. It did: the terralith-scale
// floci/scale=128 record had cold 21,423 against stock's 17,422 imported,
// and a backfill run seconds later for an unrelated reason left it with no
// call counts and no complaint. A record without plan_calls is a legitimate
// shape, so nothing downstream could have caught it either - the publishing
// side would have gone on validating and simply stopped printing the number.
//
// scaleslice.go already reasoned about this hazard from the other side,
// which is why scale-import-slice merges into an existing row rather than
// replacing it. This is the same care owed in the other direction.
func (a *ScaleArtifact) UpsertScaleRecordKeepingCallCounts(rec ScaleRecord) {
	for i := range a.Records {
		if a.Records[i].Estate != rec.Estate || a.Records[i].Target != rec.Target || a.Records[i].Scale != rec.Scale {
			continue
		}
		if rec.PlanCalls == nil {
			rec.PlanCalls = a.Records[i].PlanCalls
		}
		if rec.AuditCalls == nil {
			rec.AuditCalls = a.Records[i].AuditCalls
		}
		// The numbers are worth nothing without the sentence that says
		// where they came from, and the rebuild has just overwritten
		// Source with its own. Carry that sentence too.
		if rec.CallCountsSource == "" {
			rec.CallCountsSource = a.Records[i].CallCountsSource
		}
		break
	}
	a.UpsertScaleRecord(rec)
}

// ---------------------------------------------------------------------------
// cmdScaleBackfill: `gauntlet scale-backfill [rev...]`
// ---------------------------------------------------------------------------

// cmdScaleBackfill is issue #1051's recovery path: live/gauntlet.json's own
// live_cert array keeps only the LATEST run per estate (LiveCertResult is
// keyed by estate alone - SetLiveCertResult, livecert.go), so every earlier
// scale point terralith-scale.sh ever measured survives only in git
// history, as a row a LATER commit went on to overwrite. This walks the
// revisions named on the command line (HEAD, always, plus whichever past
// revisions the caller names - see this worker's own report for exactly
// which ones issue #1051 asks for), reads live/gauntlet.json AS IT EXISTED
// at each one with `git show`, and upserts a ScaleRecord for every
// live_cert row and (where BuildScaleRecordFromEstate recognizes it)
// `estates` row it finds - never by hand, never by re-typing a number out
// of a commit message, only by parsing the SAME committed JSON a reader
// could open themselves at that revision.
//
// A revision this checkout does not have (a shallow clone, a typo) fails
// the whole run rather than silently skipping it - a backfill that quietly
// drops a point is worse than one that refuses to run at all.
func cmdScaleBackfill(root string, args []string) error {
	revs := append([]string{"HEAD"}, args...)

	sa, err := LoadScaleArtifact(root)
	if err != nil {
		return err
	}
	if sa.Schema == 0 {
		sa.Schema = ScaleRecordSchema
	}

	for i, rev := range revs {
		b, err := gitShowFile(root, rev, ArtifactPath)
		if err != nil {
			return fmt.Errorf("scale-backfill: reading %s at %s: %w", ArtifactPath, rev, err)
		}
		var a Artifact
		if err := json.Unmarshal(b, &a); err != nil {
			return fmt.Errorf("scale-backfill: parsing %s at %s: %w", ArtifactPath, rev, err)
		}
		full, err := resolveRev(root, rev)
		if err != nil {
			return err
		}
		source := fmt.Sprintf("git show %s:%s", full, ArtifactPath)

		for _, lc := range a.LiveCert {
			rec := BuildScaleRecordFromLiveCert(lc, source)
			if rec.Scale == 0 && rec.Resources == nil {
				// Not a scale-measured live_cert row (e.g.
				// reference-ec2-vpc, which has no notion of scale) -
				// nothing to add, and nothing wrong either.
				continue
			}
			if err := ValidateScaleRecord(rec); err != nil {
				return fmt.Errorf("scale-backfill: %s: %w", rev, err)
			}
			sa.UpsertScaleRecordKeepingCallCounts(rec)
			fmt.Printf("scale-backfill: %s live_cert estate=%s target=%s scale=%d at %s\n", rev, rec.Estate, rec.Target, rec.Scale, full)
		}

		// The `estates` array, unlike `live_cert`, is not this backfill's
		// reason for walking history: an EstateResult row IS re-measured in
		// place on every `gauntlet run` (Rebuild, artifact.go), so an old
		// revision's copy is just a stale duplicate of a row HEAD's own
		// Artifact.Estates already carries, at whatever scale that estate's
		// crossing script happens to run at - which for terralith-scale has
		// always been scale=1, never the point of interest here. Reading it
		// only at revs[0] (HEAD, always first - see revs above) keeps this
		// loop from having its floci row's Source/Detail overwritten by
		// whichever PAST revision the caller happened to list last, which
		// upsertion-by-(estate,target,scale) would otherwise do silently.
		if i != 0 {
			continue
		}
		for _, e := range a.Estates {
			rec, ok := BuildScaleRecordFromEstate(e, source)
			if !ok {
				continue
			}
			if err := ValidateScaleRecord(rec); err != nil {
				return fmt.Errorf("scale-backfill: %s: %w", rev, err)
			}
			sa.UpsertScaleRecordKeepingCallCounts(rec)
			fmt.Printf("scale-backfill: %s estates estate=%s target=%s scale=%d at %s\n", rev, rec.Estate, rec.Target, rec.Scale, full)
		}
	}

	if err := SaveScaleArtifact(root, sa); err != nil {
		return err
	}
	fmt.Printf("scale-backfill: wrote %s (%d record(s))\n", ScaleRecordsPath, len(sa.Records))
	return nil
}

// resolveRev returns rev's full commit sha, so a ScaleRecord's Source names
// something a reader can `git show` themselves even when the caller passed
// a short or symbolic rev (HEAD, an abbreviated sha).
func resolveRev(root, rev string) (string, error) {
	cmd := exec.Command("git", "rev-parse", rev)
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("resolving revision %q: %w", rev, err)
	}
	return strings.TrimSpace(string(out)), nil
}
