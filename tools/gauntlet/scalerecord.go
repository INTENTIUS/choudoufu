// BuildScaleRecordFromLiveCert converts one LiveCertResult
// (live/gauntlet.json's own live_cert array) into a ScaleRecord. source
// names where r itself came from (a git revision, typically) for the
// resulting record's own Source field.
func BuildScaleRecordFromLiveCert(r LiveCertResult, source string) ScaleRecord {
	rec := ScaleRecord{
		Schema: ScaleRecordSchema,
		Estate: r.Estate,
		Target: r.Target,
		Region: r.Region,
		Commit: r.Commit,
		Date:   r.Date,
		Source: source,
	}
	if len(r.Stages) > 0 {
		rec.Stages = map[string]ScaleStage{}
	}
	for id, verdict := range r.Stages {
		detail := r.Detail[id]
		if strings.Contains(detail, "held: true") {
			rec.Held = true
		}
		st := ScaleStage{Verdict: verdict, Detail: detail}
		// Seconds - this stage's own wall-clock duration - comes ONLY from
		// the runner's own duration_s reading (r.Seconds), never from a
		// detail sentence: see ScaleStage.Seconds's own doc comment for why
		// conflating the two was the defect this file's package comment (and
		// issue #1051/#1053's wall-time-accounting unit) exists to fix.
		// Absent when r.Seconds carries nothing for this id - a run recorded
		// before LiveCertResult.Seconds existed, most historical rows today.
		if secs, ok := r.Seconds[id]; ok {
			st.Seconds = floatPtr(secs)
		}
		switch id {
		case "cold_deploy":
			resources, scale, opSeconds, throttle, retry := parseColdDeployDetail(detail)
			if resources != nil {
				rec.Resources = mergeResourcesTotal(rec.Resources, *resources)
			}
			if scale != nil {
				rec.Scale = *scale
			}
			st.OperationSeconds, st.Throttle, st.Retry = opSeconds, throttle, retry
		case "migrate":
			taggable, skipped, opSeconds, throttle, retry := parseMigrateDetail(detail)
			if taggable != nil {
				rec.Resources = mergeResourcesTaggable(rec.Resources, *taggable)
			}
			if skipped != nil {
				rec.Resources = mergeResourcesSkipped(rec.Resources, *skipped)
			}
			st.OperationSeconds, st.Throttle, st.Retry = opSeconds, throttle, retry
		case "test_plan":
			opSeconds, throttle, retry, indexLag := parseTestPlanDetail(detail)
			st.OperationSeconds, st.Throttle, st.Retry = opSeconds, throttle, retry
			if indexLag != nil {
				rec.IndexLagS = indexLag
			}
			if pc := parsePlanCallsDetail(detail); pc != nil {
				rec.PlanCalls = pc
			}
		case "test_apply":
			// Nothing promoted to a ScaleRecord field - see
			// parseTestApplyDetail's own doc comment.
		}
		rec.Stages[id] = st
	}
	if r.DurationS > 0 {
		total := r.DurationS
		rec.TotalSeconds = &total
		rec.UnaccountedSeconds = unaccountedSeconds(total, rec.Stages)
	}
	return rec
}

// BuildScaleRecordFromEstate converts one EstateResult
// (live/gauntlet.json's own `estates` array) into a ScaleRecord, when its
// name and detail text are recognizably a scale-measured run - ok is false
// otherwise (an estate this schema has no scale concept for, e.g. any
// module example that is not terralith-gen's own terralith), and no record
// is fabricated in that case.
func BuildScaleRecordFromEstate(e EstateResult, source string) (ScaleRecord, bool) {
	if e.LastRun == nil {
		return ScaleRecord{}, false
	}
	coldDetail := ""
	if e.LastRun.Detail != nil {
		coldDetail = e.LastRun.Detail["cold_deploy"]
	}
	resources, scale, _, _, _ := parseColdDeployDetail(coldDetail)
	if resources == nil {
		// This estate's cold_deploy sentence names no resource count at
		// all (every module-example estate) - not a scale-measured
		// estate, honestly reported as "nothing to build" rather than an
		// empty/zero-valued record.
		return ScaleRecord{}, false
	}
	rec := ScaleRecord{
		Schema:   ScaleRecordSchema,
		Estate:   e.Name,
		Target:   "floci",
		Scale:    0,
		Commit:   e.LastRun.Commit,
		Date:     e.LastRun.Date,
		Emulator: e.LastRun.Emulator,
		Oracle:   e.LastRun.Oracle,
		Source:   source,
	}
	if scale != nil {
		rec.Scale = *scale
	}
	rec.Resources = &ScaleResources{Total: *resources}
	if migrateDetail, ok := e.LastRun.Detail["migrate"]; ok {
		taggable, _, _, _, _ := parseMigrateDetail(migrateDetail)
		if taggable != nil {
			rec.Resources.Taggable = *taggable
			rec.Resources.Skipped = *resources - *taggable
		}
	}
	// Only the stages THIS run measured belong in a scale record, and
	// LastRun.Seconds is the witness for which those are (issue #1069).
	//
	// EstateResult.Stages is merged across runs by RunEstates (run.go), so
	// a stage this run never reached keeps an older run's verdict. On the
	// board that is right: a stale verdict is still the best thing known
	// about that stage. In a record keyed by (estate, target, SCALE) it is
	// not, because a verdict measured at one size says nothing about
	// another - and the merge is silent, so the record cannot tell the two
	// apart by inspection.
	//
	// The run that forced this was terralith-scale at SCALE=136, 10,069
	// resources: it aborted at test_plan having spoken three stages, into a
	// row carrying eleven more from a scale-1 run eleven days older. Among
	// them was test_apply, which chant-bench scores - so the published row
	// would have claimed choudoufu's apply was verified at ten thousand
	// resources when it was verified at seventy-nine.
	//
	// Seconds became a usable witness only when #1069's fix stopped it
	// being merged too; it now holds exactly the stages this run emitted a
	// duration_s for. A row that recorded no per-stage seconds at all has
	// no witness, and there every stage is kept rather than the record
	// being silently emptied - an older row with nothing to go on is a
	// weaker record, not a false one.
	measured := e.LastRun.Seconds
	for id, verdict := range e.Stages {
		if len(measured) > 0 {
			if _, ok := measured[id]; !ok {
				continue
			}
		}
		st := ScaleStage{Verdict: verdict}
		if e.LastRun.Detail != nil {
			st.Detail = e.LastRun.Detail[id]
		}
		if secs, ok := measured[id]; ok {
			st.Seconds = floatPtr(secs)
		}
		if rec.Stages == nil {
			rec.Stages = map[string]ScaleStage{}
		}
		rec.Stages[id] = st
	}
	if e.LastRun.DurationS > 0 {
		total := e.LastRun.DurationS
		rec.TotalSeconds = &total
		rec.UnaccountedSeconds = unaccountedSeconds(total, rec.Stages)
	}
	return rec, true
}

func mergeResourcesTotal(r *ScaleResources, total int) *ScaleResources {
	if r == nil {
		return &ScaleResources{Total: total}
	}
	r.Total = total
	return r
}

func mergeResourcesTaggable(r *ScaleResources, taggable int) *ScaleResources {
	if r == nil {
		return &ScaleResources{Taggable: taggable}
	}
	r.Taggable = taggable
	return r
}

func mergeResourcesSkipped(r *ScaleResources, skipped int) *ScaleResources {
	if r == nil {
		return &ScaleResources{Skipped: skipped}
	}
	r.Skipped = skipped
	return r
}

