// UnrecordedGoRel is the google family's per-type answer to
// [substrate.Substrate.Unrecorded] (the maintainer's ruling of 2026-10-20).
const UnrecordedGoRel = "internal/live/substrate/google_unrecorded_generated.go"

// UnrecordedDecision is one labelless type's answer: Creates when a create
// at an identity something already holds cannot collide, else name-held.
// Evidence says which fact of the source decided it; Unclassified marks a
// name-held answer taken for want of evidence either way.
type UnrecordedDecision struct {
	Type         string
	Creates      bool
	Evidence     string
	Unclassified bool
}

// upsertFuncRe is a Create the provider itself names an upsert.
var upsertFuncRe = regexp.MustCompile(`(?:CreateOrUpdate|CreateUpdate|Upsert|AcquireOrCreate)$`)

// deriveUnrecorded decides every type with no labels map. Types with one
// have a marker surface and never reach the question.
func deriveUnrecorded(ev Evidence, decisions []Decision) []UnrecordedDecision {
	var out []UnrecordedDecision
	for _, d := range decisions {
		if d.Labels {
			continue
		}
		u := UnrecordedDecision{Type: d.Type}
		byProv := ev.Types[d.Type]
		if len(byProv) == 0 {
			u.Evidence, u.Unclassified = "the source registers no resource by this name", true
			out = append(out, u)
			continue
		}
		// Every provider that serves the type has to say the create cannot
		// collide; the first that says otherwise decides.
		u.Creates = true
		for _, p := range sortedProviders(byProv) {
			creates, evidence, unclassified := unrecordedFrom(byProv[p])
			if u.Evidence == "" || (u.Creates && !creates) {
				u.Evidence, u.Unclassified = evidence, unclassified
			}
			u.Creates = u.Creates && creates
		}
		out = append(out, u)
	}
	return out
}

func unrecordedFrom(s Source) (creates bool, evidence string, unclassified bool) {
	post := containsStr(s.CreateMethods, "POST")
	setInPlace := !post && (containsStr(s.CreateMethods, "PATCH") || containsStr(s.CreateMethods, "PUT"))
	switch {
	case strings.HasPrefix(s.Kind, "iam_"):
		return true, "the IAM framework's create is a read-modify-write of the parent's IAM policy (setIamPolicy), which never answers alreadyExists", false
	case s.CreateAdopts:
		return true, fmt.Sprintf("%s returns the object it finds before writing anything", s.CreateFunc), false
	case s.CreateRefusesExisting != "":
		return false, fmt.Sprintf("the provider refuses a create over an existing object: %q", s.CreateRefusesExisting), false
	case s.CreateFunc != "" && upsertFuncRe.MatchString(s.CreateFunc):
		return true, fmt.Sprintf("the provider registers %s, an upsert, as its Create", s.CreateFunc), false
	case setInPlace:
		return true, fmt.Sprintf("%s sends %s, which sets the object in place", s.CreateFunc, strings.Join(s.CreateMethods, " then ")), false
	case post && (setVerbCallRe.MatchString(s.CreateCustom) || strings.HasPrefix(s.CreateCustom, "replace")):
		return true, fmt.Sprintf("%s posts to the custom method :%s, which replaces the setting", s.CreateFunc, s.CreateCustom), false
	case len(s.CreateMethods) == 0 && len(s.CreateSetCalls) > 0 && len(s.CreateNewCalls) == 0:
		return true, fmt.Sprintf("%s calls %s and creates nothing", s.CreateFunc, strings.Join(s.CreateSetCalls, ", ")), false
	case post && s.CreateCustom == "":
		return false, fmt.Sprintf("%s posts to a collection, which answers 409 alreadyExists at a held name", s.CreateFunc), false
	case post:
		return false, fmt.Sprintf("%s posts to the custom method :%s", s.CreateFunc, s.CreateCustom), false
	case len(s.CreateNewCalls) > 0:
		return false, fmt.Sprintf("%s calls %s", s.CreateFunc, strings.Join(s.CreateNewCalls, ", ")), false
	case s.CreateFunc == "":
		return false, "no Create defined in the type's own file", true
	}
	return false, fmt.Sprintf("%s sends nothing this reader classifies", s.CreateFunc), true
}

func renderUnrecorded(decisions []UnrecordedDecision) ([]byte, error) {
	creates, unclassified := 0, 0
	for _, d := range decisions {
		if d.Creates {
			creates++
		}
		if d.Unclassified {
			unclassified++
		}
	}
	var b bytes.Buffer
	b.WriteString(`// Copyright (c) The OpenTofu Authors
// SPDX-License-Identifier: MPL-2.0
// Copyright (c) 2023 HashiCorp, Inc.
// SPDX-License-Identifier: MPL-2.0

// Code generated by tools/gcp-row-gen. DO NOT EDIT.

package substrate

`)
	fmt.Fprintf(&b, `// googleUnrecordedCreates is every hashicorp/google and google-beta %s
// type with no labels map whose create at an identity something already
// holds cannot collide, read off the type's Create in the provider source
// (tools/gcp-row-gen/createwrite.go), with the fact that decided it. For
// these the 2026-10-20 ruling's unrecorded object plans the create
// ([UnrecordedCreates]). Of %d labelless types, %d are here.
var googleUnrecordedCreates = map[string]string{
`, ProviderVersion, len(decisions), creates)
	for _, d := range decisions {
		if d.Creates {
			fmt.Fprintf(&b, "\t%q: %q,\n", d.Type, d.Evidence)
		}
	}
	fmt.Fprintf(&b, `}

// googleUnrecordedNameHeld is every other labelless type, and why: a
// create at a held name that Google refuses, or (%d marked unclassified)
// no evidence either way, which takes the safe side. Each stops with the
// name-held refusal ([UnrecordedNameHeld]).
var googleUnrecordedNameHeld = map[string]string{
`, unclassified)
	for _, d := range decisions {
		if d.Creates {
			continue
		}
		ev := d.Evidence
		if d.Unclassified {
			ev = "unclassified: " + ev
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", d.Type, ev)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
