package override

import (
	"encoding/json"
	"sort"
)

// TablePath is the generated table, relative to the repository root.
const TablePath = "live/overrides.json"

// Row is one override as live/overrides.json records it.
type Row struct {
	Name             string            `json:"name"`
	Provider         string            `json:"provider"`
	Type             string            `json:"type"`
	Approach         string            `json:"approach"`
	SDK              string            `json:"sdk"`
	Upstream         string            `json:"upstream"`
	Summary          string            `json:"summary"`
	StockAlternative string            `json:"stock_alternative"`
	AlsoTracks       []string          `json:"also_tracks,omitempty"`
	ProvenOn         string            `json:"proven_on"`
	Hooks            []string          `json:"hooks"`
	Requires         map[string]string `json:"requires"`
}

type table struct {
	Comment   []string `json:"_comment"`
	Overrides []Row    `json:"overrides"`
}

// TableJSON is the content of live/overrides.json, generated from the
// registry by tools/override-gen. It is never edited by hand.
func TableJSON() ([]byte, error) {
	t := table{Comment: []string{
		"Generated by `go run ./tools/override-gen` from internal/live/override's registry.",
		"Do not edit. GitHub issue #2309: every provider behaviour override, the upstream",
		"issue it stands in for, and the provider version its proof ran against.",
	}}
	for _, o := range All() {
		r := Row{
			Name: o.Name, Provider: o.Provider, Type: o.Type,
			Approach: string(o.Approach), SDK: string(o.SDK), Upstream: o.Upstream,
			Summary: o.Summary, ProvenOn: o.ProvenOn, Requires: map[string]string{},
			StockAlternative: o.StockAlternative, AlsoTracks: o.AlsoTracks,
		}
		if o.Plan != nil {
			r.Hooks = append(r.Hooks, "plan")
		}
		if o.Apply != nil {
			r.Hooks = append(r.Hooks, "apply")
		}
		if len(o.DestroyFromConfig) > 0 {
			r.Hooks = append(r.Hooks, "destroy-from-config")
		}
		for path, ty := range o.Requires {
			r.Requires[path] = ty.FriendlyName()
		}
		t.Overrides = append(t.Overrides, r)
	}
	sort.Slice(t.Overrides, func(i, j int) bool { return t.Overrides[i].Name < t.Overrides[j].Name })
	out, err := json.MarshalIndent(t, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}
